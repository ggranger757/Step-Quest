"""Measure every egg's real pixels so thumbnails can show them all at the same size (3.3.14).

The egg art comes from two packs: the classic eggs fill a 32px frame, the elemental eggs sit in 84px frames with
different amounts of empty space (a shadow egg is ~60px tall, a sprout egg ~80px) and loose sparkle pixels around them.
For each sheet (8 wobble frames in a row) this finds the egg's body (the largest connected blob, so sparkles don't
count) in every frame, takes the box that holds it in all of them, and writes it to js/02i-eggbox.js:
    D.EGG_BOX[id] = [x, y, w, h, frameW, frameH]   (frame-local pixels)
WB.eggImg (js/06-engine.js) scales and offsets each egg so that box fills the thumbnail the same way.
Run from the project root after adding egg art:  python3 tools/egg_boxes.py
"""
import glob, json, os
from PIL import Image

FRAMES = 8

def body_box(fr):
    """bbox of the largest 8-connected blob of solid pixels"""
    W, H = fr.size; a = fr.getchannel('A').load(); seen = set(); best = None
    for y in range(H):
        for x in range(W):
            if a[x, y] < 60 or (x, y) in seen: continue
            stack = [(x, y)]; seen.add((x, y)); n = 0; bx0, by0, bx1, by1 = x, y, x, y
            while stack:
                cx, cy = stack.pop(); n += 1
                bx0, by0, bx1, by1 = min(bx0, cx), min(by0, cy), max(bx1, cx), max(by1, cy)
                for dx in (-1, 0, 1):
                    for dy in (-1, 0, 1):
                        nx, ny = cx + dx, cy + dy
                        if 0 <= nx < W and 0 <= ny < H and (nx, ny) not in seen and a[nx, ny] >= 60:
                            seen.add((nx, ny)); stack.append((nx, ny))
            if not best or n > best[0]: best = (n, (bx0, by0, bx1 + 1, by1 + 1))
    return best and best[1]

out = {}
for f in sorted(glob.glob('assets/egg/*.png')):
    im = Image.open(f).convert('RGBA'); W, H = im.size; fw = W // FRAMES
    x0 = y0 = 10 ** 9; x1 = y1 = -1
    for i in range(FRAMES):
        bb = body_box(im.crop((i * fw, 0, (i + 1) * fw, H)))
        if not bb: continue
        x0, y0, x1, y1 = min(x0, bb[0]), min(y0, bb[1]), max(x1, bb[2]), max(y1, bb[3])
    if x1 < 0: continue
    out[os.path.basename(f)[:-4]] = [x0, y0, x1 - x0, y1 - y0, fw, H]

with open('js/02i-eggbox.js', 'w') as fh:
    fh.write('/* Step Quest — where each egg actually sits in its frame (generated by tools/egg_boxes.py; do not edit). */\n')
    fh.write('WB.DATA.EGG_BOX = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'eggs measured')
